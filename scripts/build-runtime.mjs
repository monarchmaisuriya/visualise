// Builds the sandboxed-iframe tldraw runtime into server/runtime.gen.ts, and an empty `.tldr`
// document into server/empty-drawing.gen.ts. The daemon serves the runtime over plugin RPC
// (server/assets.ts). Run via `npm run build` (production) or `npm run build:dev` (development:
// tldraw runs without a licence key, as its licence allows while developing).
// Structure adapted from lerenn/paseo-excalidraw scripts/build-runtime.mjs (MIT).
import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createTLSchema } from "@tldraw/tlschema";

const RUNTIME_OUT = "server/runtime.gen.ts";
const EMPTY_OUT = "server/empty-drawing.gen.ts";
const header = "// Generated by scripts/build-runtime.mjs. Do not edit.\n";

if (process.argv.includes("--if-missing") && existsSync(RUNTIME_OUT) && existsSync(EMPTY_OUT)) {
  process.exit(0);
}
const development = process.argv.includes("--dev");
const mode = development ? "development" : "production";

// A `.tldr` with the current schema and no records; tldraw adds the document and first page on load.
const emptyDrawing = { tldrawFileFormatVersion: 1, schema: createTLSchema().serialize(), records: [] };
writeFileSync(EMPTY_OUT, `${header}export const emptyDrawingText: string = ${JSON.stringify(`${JSON.stringify(emptyDrawing, null, 2)}\n`)};\n`);

// tldraw fetches fonts, icons and translations from its CDN unless given URLs. Inline them as data
// URLs so the iframe never needs the network. Only English ships; the runtime forces locale "en".
const inlineTldrawAssets = {
  name: "inline-tldraw-assets",
  setup(b) {
    b.onLoad({ filter: /@tldraw[\\/]assets[\\/]translations[\\/][^\\/]+\.json$/ }, (args) =>
      /[\\/](en|languages)\.json$/.test(args.path)
        ? { contents: readFileSync(args.path), loader: "dataurl" }
        : { contents: 'export default ""', loader: "js" },
    );
    // tldraw picks an icon by appending `#<id>` to the sprite URL. esbuild's default SVG data URL is
    // plain text, whose own `#` characters (`fill="#000"`) would end the URL early, so use base64.
    b.onLoad({ filter: /@tldraw[\\/]assets[\\/].+\.svg$/ }, (args) => ({
      contents: `export default ${JSON.stringify(`data:image/svg+xml;base64,${readFileSync(args.path).toString("base64")}`)}`,
      loader: "js",
    }));
  },
};

const result = await build({
  entryPoints: ["runtime-src/main.tsx"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  minify: true,
  legalComments: "none",
  conditions: [mode],
  loader: { ".css": "text", ".woff2": "dataurl", ".svg": "dataurl", ".png": "dataurl" },
  define: { "process.env.NODE_ENV": JSON.stringify(mode) },
  plugins: [inlineTldrawAssets],
  logLevel: "warning",
});
const js = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
if (js.includes("cdn.tldraw.com/") && !development) {
  console.warn("note: the bundle still mentions cdn.tldraw.com; the CSP blocks any request to it");
}
// The frame never needs the network: scripts, fonts, icons and images are inline, data: or blob:.
const csp = [
  "default-src 'none'",
  "script-src 'unsafe-inline' blob:",
  "style-src 'unsafe-inline'",
  "font-src data: blob:",
  "img-src data: blob:",
  "media-src data: blob:",
  "connect-src data: blob:",
  "worker-src blob:",
].join("; ");
const html =
  `<!doctype html><html><head><meta http-equiv="Content-Security-Policy" content="${csp}"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head>` +
  '<body style="margin:0"><div id="root"></div><script>' +
  js +
  "</script></body></html>";

writeFileSync(RUNTIME_OUT, `${header}export const runtimeMode: "development" | "production" = ${JSON.stringify(mode)};\nexport const runtimeHtml: string = ${JSON.stringify(html)};\n`);
console.log(`runtime ${mode} ${(html.length / 1e6).toFixed(2)} MB`);
